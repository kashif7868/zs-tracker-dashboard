export const formatDocumentFileSize =
  (
    bytes?: number
  ): string => {
    const fileSize =
      normalizeNonNegativeNumber(
        bytes
      );

    if (
      fileSize <= 0
    ) {
      return "—";
    }

    if (
      fileSize < 1024
    ) {
      return `${Math.round(
        fileSize
      )} B`;
    }

    const kilobytes =
      fileSize / 1024;

    if (
      kilobytes < 1024
    ) {
      return `${kilobytes.toFixed(
        1
      )} KB`;
    }

    const megabytes =
      kilobytes / 1024;

    if (
      megabytes < 1024
    ) {
      return `${megabytes.toFixed(
        1
      )} MB`;
    }

    const gigabytes =
      megabytes / 1024;

    return `${gigabytes.toFixed(
      2
    )} GB`;
  };