/* =========================================================
   GENERATE DOCUMENT

   POST /documents/generate
   ========================================================= */

export const generateDocument = async (
  payload: GenerateDocumentPayload
): Promise<GenerateDocumentResult> => {
  const response =
    await api.post(
      "/documents/generate",
      prepareGeneratePayload(
        payload
      )
    );

  const data =
    extractResponseData<unknown>(
      response
    );

  const result =
    data &&
    typeof data ===
      "object"
      ? (
          data as {
            document?: unknown;

            exportedRecords?: unknown;
          }
        )
      : {};

  return {
    document:
      normalizeDocument(
        result.document
      ),

    exportedRecords:
      normalizeNonNegativeInteger(
        result.exportedRecords
      ),
  };
};

