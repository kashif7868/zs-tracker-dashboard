/* =========================================================
   DOWNLOAD DOCUMENT

   GET /documents/:documentId/download
   ========================================================= */

export const downloadDocument =
  async (
    documentId: string
  ): Promise<DownloadDocumentResult> => {
    const response =
      await api.get(
        `/documents/${encodePathValue(
          documentId
        )}/download`,
        {
          responseType:
            "blob",
        }
      );

    const blob =
      response.data instanceof Blob
        ? response.data
        : new Blob([
            response.data,
          ]);

    const contentType =
      normalizeTrimmedString(
        response.headers?.[
          "content-type"
        ]
      ) ||
      blob.type ||
      "application/octet-stream";

    const contentDisposition =
      normalizeTrimmedString(
        response.headers?.[
          "content-disposition"
        ]
      );

    let fileName =
      "project-report";

    const utf8FileNameMatch =
      contentDisposition.match(
        /filename\*=UTF-8''([^;]+)/i
      );

    const normalFileNameMatch =
      contentDisposition.match(
        /filename="?([^";]+)"?/i
      );

    if (
      utf8FileNameMatch?.[1]
    ) {
      try {
        fileName =
          decodeURIComponent(
            utf8FileNameMatch[1]
          );
      } catch {
        fileName =
          utf8FileNameMatch[1];
      }
    } else if (
      normalFileNameMatch?.[1]
    ) {
      fileName =
        normalFileNameMatch[1];
    }

    return {
      blob,

      fileName:
        fileName.trim(),

      mimeType:
        contentType,
    };
  };

/* =========================================================
   DOWNLOAD AND SAVE IN BROWSER

   UI button directly is helper ko call kar sakta hai.
   ========================================================= */

export const saveDocumentDownload =
  async (
    documentId: string
  ): Promise<void> => {
    const {
      blob,
      fileName,
    } =
      await downloadDocument(
        documentId
      );

    const objectUrl =
      URL.createObjectURL(
        blob
      );

    const anchor =
      window.document.createElement(
        "a"
      );

    anchor.href =
      objectUrl;

    anchor.download =
      fileName;

    anchor.style.display =
      "none";

    window.document.body.appendChild(
      anchor
    );

    anchor.click();

    anchor.remove();

    URL.revokeObjectURL(
      objectUrl
    );
  };

/* =========================================================
   DELETE DOCUMENT

   DELETE /documents/:documentId

   Generated file aur history record remove honge.

   Original Project, Risks aur Evidence affect nahi honge.
   ========================================================= */

export const deleteDocument =
  async (
    documentId: string
  ): Promise<DeleteDocumentResult> => {
    const response =
      await api.delete(
        `/documents/${encodePathValue(
          documentId
        )}`
      );

    const data =
      extractResponseData<unknown>(
        response
      );

    const result =
      data &&
      typeof data ===
        "object"
        ? (
            data as {
              document?: unknown;

              fileDeleted?: unknown;
            }
          )
        : {};

    return {
      document:
        normalizeDocument(
          result.document
        ),

      fileDeleted:
        result.fileDeleted ===
        true,
    };
  };

